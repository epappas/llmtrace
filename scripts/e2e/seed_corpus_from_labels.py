#!/usr/bin/env python3
"""Seed the e2e attack corpus from labeled datasets (Loop E2E-L7 of #91).

Reads the JSON datasets under `benchmarks/datasets/` and writes one
scenario YAML per row under `benchmarks/attacks/<family>/<id>.yaml`,
matching the schema in `benchmarks/attacks/schema.json`. The selection
rules and per-family target counts are encoded in `SELECTION_PLAN`
below; running the script with no arguments produces the canonical
50-scenario corpus described in issue #97.

Idempotency: existing files are NEVER overwritten (the converter
treats them as human-owned). Pass `--force` to rewrite the auto-
generated files; hand-triaged files keep their changes regardless
because the converter only writes paths that are missing or that
still carry the AUTO_GENERATED_MARKER comment header.

Usage:
    python3 scripts/e2e/seed_corpus_from_labels.py
    python3 scripts/e2e/seed_corpus_from_labels.py --force
    python3 scripts/e2e/seed_corpus_from_labels.py --regenerate-index
"""

