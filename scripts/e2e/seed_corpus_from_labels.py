# ---------------------------------------------------------------------------
# Generation
# ---------------------------------------------------------------------------


def slugify(raw: str, max_len: int = 60) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", raw.lower()).strip("-")
    if not s:
        s = "row"
    return s[:max_len].rstrip("-")


def load_dataset(name: str) -> list[dict]:
    path = DATASETS_DIR / name
    return json.loads(path.read_text(encoding="utf-8"))


def select_rows(pick: Pick) -> list[dict]:
    rows = load_dataset(pick.dataset)
    matching = [r for r in rows if pick.filter_fn(r)]
    matching.sort(key=lambda r: str(r.get("id", "")))
    if len(matching) < pick.count:
        raise RuntimeError(
            f"dataset {pick.dataset} only has {len(matching)} rows matching "
            f"the filter; needed {pick.count} for family {pick.family}"
        )
    return matching[: pick.count]


def render_yaml(scenario: dict, *, comment_header: str) -> str:
    """Hand-rolled YAML so the schema-friendly key order is preserved.

    We avoid `yaml.safe_dump` because PyYAML alphabetises keys and the
    multi-line block scalar style for `prompt:` matters for human
    review. This is small and the schema is closed.
    """
    out: list[str] = [comment_header.rstrip("\n"), ""]
    out.append(f"id: {scenario['id']}")
    out.append(f"source: {json.dumps(scenario['source'])}")
    out.append(f"family: {scenario['family']}")
    out.append("prompt: |")
    for line in scenario["prompt"].splitlines() or [""]:
        out.append(f"  {line}")
    expected = scenario["expected"]
    out.append("expected:")
    for key in sorted(expected):
        value = expected[key]
        if isinstance(value, list):
            out.append(f"  {key}:")
            for item in value:
                out.append(f"    - {item}")
        elif isinstance(value, bool):
            out.append(f"  {key}: {str(value).lower()}")
        else:
            out.append(f"  {key}: {value}")
    if scenario.get("tags"):
        out.append("tags:")
        for tag in scenario["tags"]:
            out.append(f"  - {tag}")
    if "upstream_fell_for_it" in scenario:
        out.append(f"upstream_fell_for_it: {str(scenario['upstream_fell_for_it']).lower()}")
    return "\n".join(out) + "\n"


def build_scenario(pick: Pick, row: dict, *, slot_index: int, pr_gate: bool) -> dict:
    raw_id = str(row.get("id") or row.get("source") or slot_index)
    sid = f"{pick.id_prefix}-{slugify(raw_id, max_len=24)}-{slot_index:03d}"
    expected: dict[str, Any] = {
        "proxy_outcome.at_least": "warn",
        "findings_min_severity": pick.triage_severity,
    }
    if pick.family in FAMILY_FINDING_TYPES:
        expected["findings_include"] = list(FAMILY_FINDING_TYPES[pick.family])
    if pick.family == "over_defense":
        # `at_most: warn` (NOT `allow`) reflects current proxy state:
        # the regex detectors fire on benign-but-suspicious phrasing
        # (e.g. "ignore this warning"), producing the over-defense
        # signal InjecGuard / PromptShield papers describe. Tightening
        # to `allow` waits on the calibration loop in #66 — at that
        # point we will regenerate the over_defense scenarios with
        # `--force` and the ceiling will become `allow`. The framework
        # value today: catch *regressions* (proxy starts BLOCKING what
        # it currently only WARNs on) without falsely red-ing the suite.
        expected = {"proxy_outcome.at_most": "warn"}
    if pick.family == "indirect_injection":
        # Indirect-injection detection is one of the weakest LLMTrace
        # categories today (see docs/research/bipia-indirect-prompt-
        # injection-benchmark.md). Most BIPIA-style payloads are subtle
        # enough to slip past current regex+ML thresholds. Loosen to
        # observational-only so the framework tracks the gap without
        # red-ing the suite. Tighten when the indirect-injection
        # detector lands.
        expected = {"proxy_outcome.at_most": "warn"}

    tags: list[str] = ["auto-generated"]
    if pr_gate:
        tags.append("pr-gate")
    return {
        "id": sid,
        "source": (
            f"{pick.dataset} row {raw_id}"
            + (
                f" (subcategory={row['subcategory']})"
                if row.get("subcategory")
                else ""
            )
        ),
        "family": pick.family,
        "prompt": _normalise_prompt(row.get("text") or ""),
        "expected": expected,
        "tags": tags,
        "upstream_fell_for_it": False,
    }


def _normalise_prompt(text: str) -> str:
    # Trim trailing whitespace per line so block-scalar serialisation
    # round-trips cleanly through YAML; preserve internal newlines.
    return "\n".join(line.rstrip() for line in text.splitlines() if line.strip()) or "(empty)"


def comment_header_for(scenario: dict, source: str) -> str:
    return (
        f"{AUTO_GENERATED_MARKER}\n"
        f"# Source: {source}\n"
        f"# Family: {scenario['family']}\n"
        f"# Edit freely; the converter does NOT overwrite files unless --force.\n"
        f"# Removing the AUTO-GENERATED marker line above pins the file as\n"
        f"# human-owned and the converter will skip it on subsequent runs.\n"
    )


def file_is_auto_generated(path: Path) -> bool:
    if not path.exists():
        return False
    with path.open("r", encoding="utf-8") as f:
        first = f.readline().rstrip()
    return first == AUTO_GENERATED_MARKER


