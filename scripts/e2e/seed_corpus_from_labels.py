# INDEX.md
# ---------------------------------------------------------------------------


INDEX_HEADER = """# Attack Scenario Index

> Auto-generated by `scripts/e2e/seed_corpus_from_labels.py --regenerate-index`.
> Edit the source scenarios and re-run to refresh.

| ID | Family | Source | Tags | Prompt preview |
|---|---|---|---|---|
"""


def regenerate_index() -> None:
    import yaml  # local import keeps top-level deps minimal

    rows: list[tuple[str, str, str, str, str]] = []
    for path in sorted(ATTACKS_DIR.rglob("*.yaml")):
        scenario = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(scenario, dict):
            continue
        sid = scenario.get("id") or "<missing>"
        family = scenario.get("family") or "<missing>"
        source = scenario.get("source") or "<missing>"
        tags = ", ".join(scenario.get("tags") or [])
        preview = (scenario.get("prompt") or "").splitlines()[0]
        if len(preview) > 80:
            preview = preview[:77] + "..."
        rows.append((sid, family, source, tags, preview))
    rows.sort(key=lambda r: (r[1], r[0]))
    rendered = INDEX_HEADER
    for sid, family, source, tags, preview in rows:
        sid_md = f"`{sid}`"
        family_md = f"`{family}`"
        tags_md = f"`{tags}`" if tags else ""
        rendered += (
            f"| {sid_md} | {family_md} | {_md_escape(source)} | "
            f"{tags_md} | {_md_escape(preview)} |\n"
        )
    INDEX_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {INDEX_PATH.relative_to(REPO_ROOT)} ({len(rows)} scenarios)")


def _md_escape(text: str) -> str:
    return text.replace("|", "\\|")


# ---------------------------------------------------------------------------
# Driver
# ---------------------------------------------------------------------------


def emit_pick(pick: Pick, *, force: bool, pr_gate_quota: dict[str, int]) -> int:
    written = 0
    for slot_index, row in enumerate(select_rows(pick), start=1):
        pr_gate = pr_gate_quota.get(pick.family, 0) > 0
        scenario = build_scenario(pick, row, slot_index=slot_index, pr_gate=pr_gate)
        target = ATTACKS_DIR / scenario["family"] / f"{scenario['id']}.yaml"
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists() and not force and not file_is_auto_generated(target):
            print(f"skip (human-owned)   {target.relative_to(REPO_ROOT)}")
            continue
        if target.exists() and not force:
            # File exists AND is auto-generated AND --force not given:
            # leave it alone (idempotent default).
            print(f"skip (already)       {target.relative_to(REPO_ROOT)}")
            continue
        body = render_yaml(
            scenario, comment_header=comment_header_for(scenario, scenario["source"])
        )
        target.write_text(body, encoding="utf-8")
        if pr_gate:
            pr_gate_quota[pick.family] -= 1
        written += 1
        print(f"wrote                {target.relative_to(REPO_ROOT)}")
    return written


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--force",
        action="store_true",
        help="Rewrite auto-generated files even when they already exist.",
    )
    parser.add_argument(
        "--regenerate-index",
        action="store_true",
        help="Skip generation; just rewrite benchmarks/attacks/INDEX.md from the filesystem.",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    if args.regenerate_index:
        regenerate_index()
        return 0

    pr_gate_quota = dict(PR_GATE_PER_FAMILY)
    total = 0
    for pick in SELECTION_PLAN:
        total += emit_pick(pick, force=args.force, pr_gate_quota=pr_gate_quota)
    print(f"\nGenerated {total} scenario file(s).")
    regenerate_index()
    return 0


if __name__ == "__main__":
    sys.exit(main())
